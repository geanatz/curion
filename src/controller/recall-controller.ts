/**
 * Run the narrow MVP `recall` pipeline.
 *
 * Public MCP API is unchanged. This function is consumed by
 * `src/tools/recall.ts`. The controller never throws on expected
 * failure paths; it returns a discriminated union.
 *
 * Important behavior:
 *   - If no stored memory passes the relevance threshold, the
 *     provider is NOT called. We return `no_memory`.
 *   - If the query contains a secret-shaped fragment, the provider
 *     is NOT called and the query is NOT used for retrieval. We
 *     return `rejected` (the public message does not echo the
 *     query). The query text is not logged.
 *   - If the provider fails, we return `provider_error` with a
 *     short, redacted reason. We never fabricate an answer.
 *   - If the provider's answer is empty or contains a
 *     secret-shaped fragment or a raw-dump shape, we return
 *     `provider_error`. We never expose an unsafe public answer.
 */
export async function runRecallController(
  storage: StorageHandle,
  query: string,
  options: RecallControllerOptions = {}
): Promise<RecallOutcome> {
  const threshold = options.relevanceThreshold ?? DEFAULT_RELEVANCE_THRESHOLD;
  const topK = options.topK ?? DEFAULT_TOP_K;
  const storageLimit = options.storageLimit ?? 200;

  // -- 1. Safety pre-check on the query -------------------------------
  //
  // Decision (safer temporary default): reject queries that contain
  // obvious secrets. This matches the remember controller's policy
  // on inputs: secret-shaped fragments must not be forwarded to a
  // provider or used to search storage. The MCP schema already
  // rejects empty queries at the tool boundary; we add this layer
  // as defense in depth. The public message does not echo the
  // query.
  const safety = classifyInput(query);
  logger.debug(`recall: pre-check class=${safety.class} reason=${safety.reason}`);
  if (safety.class === "secret") {
    return {
      status: "rejected",
      reason: "query contains a secret-shaped fragment; refusing to search or forward it",
      safetyClass: "secret",
    };
  }
  if (safety.class === "mixed-safe-sensitive") {
    return {
      status: "rejected",
      reason:
        "query mixes safe and sensitive fragments; please rephrase the query to remove the sensitive part",
      safetyClass: "mixed-safe-sensitive",
    };
  }
  // Note: we intentionally do NOT route prompt-injection /
  // unsafe-preference / raw-dump / self-conflict / vague-junk
  // inputs to a hard reject here. The recall path is read-only
  // and read-only queries are less dangerous than remember
  // inputs (no persistence, no per-record mutation). A vague
  // query simply yields no matches. The downstream lexical
  // ranker handles them naturally.

  // -- 2. Read safe stored summaries ----------------------------------
  const summaries = listActiveMemorySummaries(storage, {
    limit: storageLimit,
  });
  logger.debug(`recall: read ${summaries.length} safe summary(ies) from storage`);
  // Parallel lookup of stored `relationship` blocks
  // (Phase C). The controller uses this only for the
  // internal `internalAmbiguity` field on the answered
  // outcome. The public recall pipeline does not surface
  // these blocks in any other way. The two read functions
  // share the same `state = 'active'` filter and the same
  // ascending `id` order, so the controller can project
  // the block onto a candidate by id lookup below.
  const relationshipBlocks = listActiveMemoryRelationshipBlocks(storage, {
    limit: storageLimit,
  });
  const blockById = new Map<number, (typeof relationshipBlocks)[number]["block"]>();
  for (const r of relationshipBlocks) {
    blockById.set(r.id, r.block);
  }

  // -- Phase 3A trace: active memory read --------------------------------
  emitActiveMemoryReadStage(options.trace, {
    readCount: summaries.length,
    storageLimit,
  });

  // -- 3. Lexical ranking ---------------------------------------------
  // Run lexical ranking on ALL summaries (not limited by topK) to build
  // the candidate pool for semantic fusion AND the adaptive-depth
  // stage. Using storageLimit as the lexical topK limit gives
  // semantic the broadest possible pool to recover paraphrase hits
  // that lexical would miss, and gives the adaptive-depth stage a
  // large ranked pool to select from (narrow queries still feel
  // tight because the relative-fraction cluster and the elbow cut
  // exclude weak candidates; broad queries grow because the
  // cluster survives the cut).
  //
  // The legacy `topK` cap is honoured at the adaptive-depth stage
  // (`maxK` defaults to 15, well above the legacy 5). The narrow
  // behaviour is preserved: a single dominant memory is still kept
  // at the top, just with a defensible minK=3 floor below it.
  const lexicalTopK = storageLimit;
  const ranked: LexicalScoredCandidate[] = rankLexical(
    query,
    summaries.map((s: SafeMemorySummary) => ({
      id: s.id,
      text: s.memoryContent,
      tags: s.tags,
    })),
    { threshold, topK: lexicalTopK }
  );
  // Build the id->summary map once; used by both the trace
  // event and the topSummaries construction below.
  const summaryById = new Map<number, SafeMemorySummary>(summaries.map((s) => [s.id, s]));
  // -- Phase 3A trace: lexical ranking (before demotion) ----------------
  // The trace records the raw lexical ranking; the demotion
  // is a pure post-rank step that only reorders candidates
  // when superseded relationships exist in the candidate set.
  emitLexicalRankingStage(options.trace, {
    query,
    threshold,
    topK: lexicalTopK,
    ranked,
    summariesById: summaryById,
  });

  // -- 3b. Semantic retrieval and hybrid fusion -------------------------
  // When semanticEnabled is true OR an embedder is explicitly injected,
  // run semantic scoring on the broadest possible pool (all summaries
  // with embeddings) and fuse with lexical. This allows semantic to
  // recover paraphrase hits that lexical topK would not include.
  //
  // Behavior:
  //   - semanticEmbedder injected (tests): use it directly, no internal creation.
  //   - semanticEnabled only: controller creates embedder internally (tool-layer
  //     design — controller does NOT create heavy defaults).
  //   - Neither: semantic path is skipped (lexical-only).
  let finalRanked = ranked;
  const shouldRunSemantic = options.semanticEmbedder != null || options.semanticEnabled;
  if (shouldRunSemantic) {
    try {
      // Use injected embedder if provided; otherwise create one internally.
      const embedder =
        options.semanticEmbedder ?? (await createSemanticEmbedder({ enabled: true }));
      // Only proceed if embedder is ready (not error status)
      if (embedder.metadata.status === "ready") {
        // Get embeddings for ALL summaries that have them, not just topK.
        // This is the key: semantic should see the full active pool.
        const allMemoryIds = summaries.map((s) => s.id);
        const embeddings = getEmbeddingsForMemories(storage, allMemoryIds);
        if (embeddings.size > 0) {
          // Embed the query once.
          const queryVec = await embedder.embed(query, "query");
          // Score ALL candidates that have embeddings.
          const semCandidates = Array.from(embeddings.values()).map((e) => ({
            id: e.memoryId,
            vec: e.vec,
          }));
          const semRanked = scoreSemanticCandidates(queryVec, semCandidates);
          // Fuse semantic with lexical. Use weights that favor semantic
          // slightly for paraphrase recovery while preserving lexical signal.
          const fused = fuseLexicalAndSemantic(
            ranked,
            semRanked,
            { lexical: 1, semantic: 1 },
            60, // RRF k constant
            storageLimit // Consider top storageLimit candidates in fusion
          );
          finalRanked = fused;
          logger.debug(
            `recall: semantic fused ${ranked.length} lexical + ${semRanked.length} semantic -> ${fused.length} final`
          );
        } else {
          logger.debug("recall: semantic enabled but no embeddings stored");
        }
      } else {
        logger.debug(`recall: semantic embedder not ready (status: ${embedder.metadata.status})`);
      }
    } catch (err) {
      // Non-fatal: fall back to lexical-only if semantic fails.
      logger.debug(
        `recall: semantic retrieval failed: ${(err as Error).message}; falling back to lexical`
      );
    }
  }

  // Early exit check AFTER semantic fusion.
  // When semantic is enabled, we defer the check until after fusion
  // so semantic can recover memories that lexical threshold filtered out.
  if (finalRanked.length === 0) {
    logger.debug("recall: no relevant memory; skipping provider call");
    // Add clarification for obviously vague/underspecified queries.
    if (isVagueQuery(query)) {
      return {
        status: "no_memory",
        clarification_needed: {
          question:
            "Could you be more specific about what you're looking for? For example, what topic or project was this about?",
        },
      };
    }
    return { status: "no_memory" };
  }

  // -- 3c. Superseded-memory demotion -----------------------------------
  // When both a superseding candidate (A) and its superseded target (B)
  // are present in the ranked set, demote B so A ranks higher.
  // Missing references are silently ignored. The demotion is a pure
  // reordering step; no I/O, no state change.
  const scoredWithRelationships: ScoredCandidateWithRelationship[] = finalRanked.map((r) => {
    const block = blockById.get(r.id);
    return block === undefined
      ? { id: r.id, score: r.score }
      : {
          id: r.id,
          score: r.score,
          relationship: {
            supersedes: block.supersedes,
            supersededBy: block.supersededBy,
          },
        };
  });
  const demotedRanked = demoteSupersededMemories(scoredWithRelationships);

  // -- Phase 3A trace: superseded demotion --------------------------------
  // Compute the stale-id set and superseding-id map from the scored
  // candidates so the trace event can summarize what was demoted and why.
  // This mirrors the logic in `demoteSupersededMemories` but surfaces
  // the intermediate data for tracing.
  const candidateIds = new Set<number>(scoredWithRelationships.map((c) => c.id));
  const demotedIds = new Set<number>();
  const supersededByMap = new Map<number, number>(); // staleId -> supersedingId
  for (const c of scoredWithRelationships) {
    const rel = c.relationship;
    if (!rel) continue;
    if (rel.supersedes) {
      for (const otherId of rel.supersedes) {
        if (typeof otherId !== "number" || !Number.isFinite(otherId)) continue;
        if (candidateIds.has(otherId)) {
          demotedIds.add(otherId);
          // reason for otherId is "supersededBy"; supersedingId is c.id
          supersededByMap.set(otherId, c.id);
        }
      }
    }
    if (rel.supersededBy) {
      for (const otherId of rel.supersededBy) {
        if (typeof otherId !== "number" || !Number.isFinite(otherId)) continue;
        if (candidateIds.has(otherId)) {
          demotedIds.add(c.id);
          // reason for c.id is "supersededBy"; supersedingId is otherId
          supersededByMap.set(c.id, otherId);
        }
      }
    }
  }
  emitSupersededDemotionStage(options.trace, {
    before: ranked.map((r) => ({ id: r.id, score: r.score })),
    after: demotedRanked.map((r) => ({ id: r.id, score: r.score })),
    demotedIds,
    supersededByMap,
  });

  // Re-attach summaries in the order returned by the demoted ranker.
  // demotedRanked carries the score-sorted order (post-demotion).
  // We use a single O(N) map lookup so this stays linear even if
  // the store grows. The relationship block (Phase C) is
  // attached as an optional extension; rows without a stored
  // block carry `relationship: undefined` and the detector
  // treats them as having no stored data (it can still fire
  // on the lexical / asymmetric-negation path).
  const candidatePool: SafeMemorySummaryWithRelationship[] = [];
  for (const r of demotedRanked) {
    const s = summaryById.get(r.id);
    if (!s) continue;
    const block = blockById.get(r.id);
    candidatePool.push(block === undefined ? { ...s } : { ...s, relationship: { ...block } });
  }
  // Sanity: every ranked id must have a summary. If this ever
  // fails, it means a memory was deleted between the read and
  // the rank — fall back to no_memory rather than fabricating.
  if (candidatePool.length !== demotedRanked.length) {
    logger.debug("recall: ranked-id missing summary (storage raced); returning no_memory");
    return { status: "no_memory" };
  }

  // -- 3d. Adaptive recall depth (experimental) -----------------------
  // The production recall pipeline currently caps synthesis at a
  // fixed topK=5 (see `DEFAULT_TOP_K` in `src/retrieval/lexical.ts`).
  // Narrow precise queries want that tight cap. Broad / vague
  // queries, or queries with many closely relevant memories, want
  // more — but the synthesis prompt must remain bounded.
  //
  // The `runAdaptiveDepth` helper replaces the fixed cap with a
  // deterministic, score-driven selection (default: elbow
  // strategy, minK=3, maxK=15, relative-fraction=0.5) followed by
  // an optional diversity filter and an explicit prompt-budget
  // step. The defaults are conservative and quality-oriented:
  // narrow queries stay tight, broad queries grow up to a capped
  // maximum, noisy tail candidates are excluded, and the synthesis
  // prompt cannot exceed the per-memory and total budgets.
  //
  // The adaptive-depth stage is purely internal to the controller.
  // The public `recall(text)` API is unchanged. Superseded
  // candidates are still demoted above this stage (so they are
  // naturally excluded by the relative / absolute cluster).
  const rankedWithText: AdaptiveCandidateWithText[] = candidatePool.map((s) => {
    // Find the score from demotedRanked (the demoted order) so
    // demoted candidates carry their (already-demoted) score.
    const demotedEntry = demotedRanked.find((r) => r.id === s.id);
    return {
      id: s.id,
      score: demotedEntry?.score ?? 0,
      text: s.memoryContent,
      ...(Array.isArray(s.tags) && s.tags.length > 0 ? { tags: s.tags } : {}),
    };
  });
  const depthResult = runAdaptiveDepth(
    rankedWithText,
    options.adaptiveDepth ?? DEFAULT_ADAPTIVE_DEPTH_PIPELINE_CONFIG
  );
  // Project the kept candidates back to SafeMemorySummaryWithRelationship.
  // Preserve score-desc order so the synthesis prompt sees the
  // highest-scoring memories first. The relationship block is
  // reattached (Phase C) so the ambiguity / resolved-history
  // detectors see the same metadata they did before this phase.
  const selectedIds = new Set(depthResult.selected.map((c) => c.id));
  const topSummaries: SafeMemorySummaryWithRelationship[] = depthResult.selected.map((c) => {
    const original = candidatePool.find((s) => s.id === c.id);
    // original is guaranteed present: selectedIds came from
    // rankedWithText, which came from candidatePool. Defensive
    // fall-through keeps the projection total in the impossible
    // race condition where the storage layer mutates between
    // steps.
    if (!original) {
      return {
        id: c.id,
        kind: "fact",
        state: "active",
        memoryContent: c.text,
        tags: c.tags ?? [],
        classification: null,
        confidence: null,
      };
    }
    return original;
  });
  logger.debug(
    `recall: adaptive-depth kept ${topSummaries.length}/${candidatePool.length} candidate(s) (${depthResult.trace.selector.reason})`
  );

  // -- Phase 3A trace: adaptive-depth + prompt-budget ------------------
  // Debugging instrumentation: emit the full adaptive-depth /
  // prompt-budget decision (counts, scores, kinds, content
  // lengths, dropped / truncated counts, totals) BEFORE the
  // `selected-candidates` event so a reader can correlate the
  // selector's decision with the final synthesis input. The
  // helper short-circuits when tracing is disabled; the
  // controller's behavior is unchanged when trace is off. The
  // kindsById map is built from `candidatePool` (the post-
  // demotion summary view) so the `keptKinds` field on the
  // trace event carries the kind of each kept memory without
  // leaking its content.
  const kindsById = new Map<number, string>();
  for (const s of candidatePool) {
    kindsById.set(s.id, s.kind);
  }
  emitAdaptiveDepthStages(options.trace, {
    rankedWithText,
    depthResult,
    config: options.adaptiveDepth ?? DEFAULT_ADAPTIVE_DEPTH_PIPELINE_CONFIG,
    kindsById,
  });

  // -- Phase 3A trace: selected candidates -----------------------------
  emitSelectedCandidatesStage(options.trace, topSummaries);

  // -- 4. Provider synthesis -----------------------------------------
  const adapterOptions: RecallSynthesisOptions = {};
  if (options.providerFetchImpl !== undefined) {
    adapterOptions.fetchImpl = options.providerFetchImpl;
  }
  if (options.providerPrimaryApiKey !== undefined) {
    adapterOptions.primaryApiKey = options.providerPrimaryApiKey;
  }
  if (options.providerFallbackApiKey !== undefined) {
    adapterOptions.fallbackApiKey = options.providerFallbackApiKey;
  }
  if (options.providerPrimaryBaseUrl !== undefined) {
    adapterOptions.primaryBaseUrl = options.providerPrimaryBaseUrl;
  }
  if (options.providerFallbackBaseUrl !== undefined) {
    adapterOptions.fallbackBaseUrl = options.providerFallbackBaseUrl;
  }
  if (options.providerPrimaryModel !== undefined) {
    adapterOptions.primaryModel = options.providerPrimaryModel;
  }
  if (options.providerFallbackModel !== undefined) {
    adapterOptions.fallbackModel = options.providerFallbackModel;
  }

  const memories: RecallMemoryInput[] = topSummaries.map((s) => ({
    id: s.id,
    memoryContent: s.memoryContent,
    kind: s.kind,
    tags: s.tags,
  }));

  // -- 4. Provider synthesis (instrumented) -----------------------------
  // The synthesis call is timed so the trace event can record
  // `durationMs`. The helper below (dispatchSynthesisOutcome)
  // emits a single `recall.synthesis` event after the call
  // completes and before the controller returns, regardless
  // of which outcome branch is taken. The event carries:
  //
  //   - status           : "ok" | "error" | "weak" | "refusal"
  //   - providerUsed     : when the call returned a typed result
  //   - fallbackUsed     : true if the fallback slot produced the result
  //   - modelUsed        : when the call returned a typed result
  //   - durationMs       : wall-clock around synthesizeRecallWithFallback
  //   - errorKind        : sanitized ProviderErrorKind OR validation reason
  //   - errorMessage     : truncated, sanitized message
  //   - answerPresent    : true iff the provider returned a non-empty answer
  //   - answerLength     : length of the raw provider answer (no content)
  //   - refusalDetected  : true iff the refusal-shape detector fired
  //   - errorReasoningOnly: true iff the failure is the reasoning-only path
  //   - candidateCount   : how many memories the prompt was built from
  //   - promptMemoryCharTotal: total chars sent in the MEMORIES section
  //   - httpCalls        : number of provider HTTP calls
  //
  // The payload intentionally omits the raw answer text, the raw
  // reasoning text, the raw prompt body, the raw memory text, and
  // any API key. The writer's central `redactPayload` pass still
  // applies as defense in depth. This event is instrumentation
  // only: the controller's behavior, the public outcome, and the
  // on-the-wire projection are unchanged.
  const synthStartMs = Date.now();
  const result: RecallSynthesisResult = await synthesizeRecallWithFallback(
    query,
    memories,
    adapterOptions
  );
  const synthDurationMs = Math.max(0, Date.now() - synthStartMs);

  // Sum of the post-budget memory text lengths that the synthesis
  // prompt was built from. We use `depthResult.selected` because
  // that is the authoritative "what was sent to the model" set
  // (selector + diversity + budget have already run). This is a
  // diagnostic number on the trace event; no text content is
  // included.
  const promptMemoryCharTotal = depthResult.selected.reduce(
    (acc, c) => acc + (typeof c.text === "string" ? c.text.length : 0),
    0
  );

  // Dispatch the synthesis result through the controller's
  // classification pipeline (validateAnswer + refusal-with-thin-
  // match reroute + provider_error branches) and emit the
  // synthesis trace event. The helper does NOT mutate the
  // public outcome shape; it only classifies and emits.
  const dispatch = dispatchSynthesisOutcome({
    result,
    query,
    topSummaries,
    finalRanked,
    trace: options.trace,
    synthDurationMs,
    candidateCount: memories.length,
    promptMemoryCharTotal,
  });

  if (dispatch.kind === "no_answer") {
    return dispatch.outcome;
  }
  // Use the redacted form so any secret-shaped fragment the
  // model produced (defense in depth) is removed before we hand
  // the text to the tool layer. The validator above already
  // rejected answers that are entirely or mostly redacted.
  const safeAnswer = dispatch.safeAnswer;

  // -- 5. Internal ambiguity detection (Phase C) ----------------------
  // Conservative offline detector. The signal is attached
  // to the answered outcome as an internal-only field.
  // `src/tools/recall.ts` is responsible for dropping it
  // from the public projection. The public message / answer
  // remain byte-equal to pre-Phase-C for every status
  // branch. The detector does NOT short-circuit the
  // pipeline; the provider call above always runs.
  const internalAmbiguity: AmbiguitySignal = detectAmbiguity({
    topCandidates: topSummaries,
    answer: safeAnswer,
  });

  // -- 6. Internal resolved-history detection (Phase H + J) -----------
  // Conservative offline detector that recognises an
  // **explicit** resolution marker pair (`previous` /
  // `old` / `superseded` / `no longer` on the previous
  // side; `current` / `replaced` on the current side),
  // with a referential-pointer variant (Pattern B in spec
  // §5.2). The detector is structurally parallel to the
  // Phase C ambiguity detector above but uses a different
  // rule set; the two signals live on separate internal
  // fields on the answered outcome (see the
  // `internalResolvedHistory` field on `RecallOutcome`).
  // The detector does NOT short-circuit the pipeline.
  // `src/tools/recall.ts` is responsible for the public
  // projection: it composes `formatAmbiguityNote` and
  // `formatResolvedHistoryNote` into a single prefix on
  // the public `message` (the ambiguity note takes
  // precedence per spec §4.2 / §4.3: a stored conflict
  // pointer wins, and the detector stays silent on
  // resolved-history when the Phase D detector would
  // fire). When both notes are empty, the public
  // `message` is byte-equal to the synthesized answer
  // (pre-Phase-J invariant, preserved for the no-detector
  // case).
  const internalResolvedHistory: ResolvedHistorySignal = detectResolvedHistory({
    topCandidates: topSummaries,
    answer: safeAnswer,
  });

  return {
    status: "answered",
    answer: safeAnswer,
    sourceIds: topSummaries.map((s) => s.id),
    internalAmbiguity,
    internalResolvedHistory,
  };
}

